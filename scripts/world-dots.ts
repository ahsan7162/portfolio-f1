// Builds src/art/worldDots.ts: the Contact section's dotted world map, worked out once here
// instead of in the browser (svg-dotted-map takes seconds on a phone and froze the page).
// Run after changing the map size or the markers: npx tsx scripts/world-dots.ts
import { writeFileSync } from 'node:fs';
import { createMap } from 'svg-dotted-map';

const W = 150, H = 75, SAMPLES = 3000, R = 0.25;
const MARKERS = [
  { lat: 24.86, lng: 67.0, size: 1.4, pulse: true }, // Karachi
  { lat: 25.2, lng: 55.27, size: 1 },               // Dubai (Careem)
  { lat: 45.46, lng: 9.19, size: 1 },               // Milan (Xtel, remote)
];

const { points, addMarkers } = createMap({ width: W, height: H, mapSamples: SAMPLES });

// Every other row shifts half a step, as in Magic UI's DottedMap.
const rows = [...new Set(points.map(p => p.y))].sort((a, b) => a - b);
const rowOf = new Map(rows.map((y, i) => [y, i]));
let step = Infinity;
for (const y of rows) {
  const xs = points.filter(p => p.y === y).map(p => p.x).sort((a, b) => a - b);
  for (let i = 1; i < xs.length; i++) if (xs[i] - xs[i - 1] > 0) step = Math.min(step, xs[i] - xs[i - 1]);
}
if (!Number.isFinite(step)) step = 1;
const shift = (x: number, y: number) => x + ((rowOf.get(y) ?? 0) % 2 === 1 ? step / 2 : 0);
const n = (v: number) => +v.toFixed(2);

// All dots as one path of zero-length strokes (round caps draw each as a dot of
// diameter 2R): one DOM node instead of a thousand circles.
const dots = points.map(p => `M${n(shift(p.x, p.y))} ${n(p.y)}h0`).join('');
const markers = addMarkers(MARKERS).map(m => ({ x: n(shift(m.x, m.y)), y: n(m.y), r: m.size ?? R, pulse: !!m.pulse }));

writeFileSync('src/art/worldDots.ts', `// Generated by scripts/world-dots.ts. Do not edit.
export const WORLD = { width: ${W}, height: ${H}, dot: ${2 * R} } as const;
export const WORLD_DOTS = ${JSON.stringify(dots)};
export const WORLD_MARKERS = ${JSON.stringify(markers)};
`);
console.log(`${points.length} dots, ${markers.length} markers, ${(dots.length / 1024).toFixed(1)} KB path`);
